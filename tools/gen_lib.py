#!/usr/bin/env python3
"""gen_lib.py — src/lib.axle, the wiring header.

    python3 tools/gen_lib.py           # rewrite src/lib.axle
    python3 tools/gen_lib.py --check   # fail if a module is missing from it

The build pulls a module into the compilation unit only if something names it, and the library's
public names (`zaffre::Button`) are the ones its root imports. So the root names every module, one
`use` per directory, bottom layer first — which is also the order doc/ARCHITECTURE.md lists them in.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "src")
LAYERS = ["core", "raw", "sys", "system", "proc", "net", "fs", "desk", "diag"]
PORTS = ("win32", "linux")

HEADER = """// gesso — what an operating system exposes, as one library for Axle.
//
// This file is the crate's wiring header: it names every module so the build pulls the whole tree
// into the compilation unit, and so the library's public names are the ones a program imports
// from `gesso`. It carries no logic and is GENERATED by `tools/gen_lib.py` — `--check` fails a
// tree where a module is missing from it.
//
// Layers, bottom to top — a module imports from below, never from above or from a sibling
// (doc/ARCHITECTURE.md, tools/check.py):
//
//   core     the vocabulary: errors, privileges, support, plans, keys, time, units, watchers
//   raw      raw memory, buffers and UTF-16: every `unsafe` in the library is here
//   sys      the seams: one answer per port (src/sys/win32, src/sys/linux), every `extern "C"` is here
//   system   the machine: CPU, memory, uptime, battery, host
//   proc     processes, threads, priority, affinity, environment
//   net      interfaces, addresses, routes, sockets, DNS, statistics
//   fs       watchers, volumes, permissions, links, atomic operations
//   desk     notifications, clipboard, hotkeys, windows, the session
//   diag     logs, events, crash reports, counters
"""


def modules():
    """Every module the root may name. A module that only some ports implement (`libc`, `kernel32`) is
    left out: the build refuses a root that imports a module a port does not carry, and such a module
    is reached anyway, from the port's own seam files that import it."""
    out = {}
    for layer in LAYERS:
        d = os.path.join(SRC, layer)
        found = {}
        for dp, _, files in os.walk(d):
            parts = os.path.relpath(dp, SRC).split(os.sep)
            port = next((p for p in parts if p in PORTS), None)
            for f in sorted(files):
                if f.endswith(".axle"):
                    rel = [p for p in parts if p not in PORTS] + [f[:-5]]
                    found.setdefault(tuple(rel), set()).add(port)
        names = []
        for rel, ports in found.items():
            if None in ports or ports >= set(PORTS):
                names.append(list(rel))
        out[layer] = sorted(names)
    return out


def use_lines(prefix, names, width=100):
    """`use crate::<prefix>::{a, b, …};` on one line when it fits, else one indented line per run of names."""
    one = "use crate::%s::{%s};" % (prefix, ", ".join(names))
    if len(one) <= width:
        return [one]
    out = ["use crate::%s::{" % prefix]
    cur = "   "
    for n in names:
        piece = " " + n + ","
        if len(cur) + len(piece) > width:
            out.append(cur)
            cur = "   "
        cur += piece
    out.append(cur)
    out.append("};")
    return out


def render():
    lines = []
    for layer, mods in modules().items():
        by = {}
        for m in mods:
            by.setdefault("::".join(m[:-1]), []).append(m[-1])
        for prefix, names in sorted(by.items()):
            lines.extend(use_lines(prefix, names))
        lines.append("")
    return HEADER + "\n".join(lines).rstrip() + "\n"


def main():
    path = os.path.join(SRC, "lib.axle")
    text = render()
    if "--check" in sys.argv:
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if have != text:
            sys.stderr.write("gen_lib: src/lib.axle is not what the tree makes\n")
            sys.exit(1)
        return
    open(path, "w", encoding="utf-8").write(text)
    print("wrote src/lib.axle")


main()
